"""Extract static, MIT-licensed dictionaries. No fake contacts generated here."""

import csv
import importlib
import importlib.metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"


def write(name, rows):
    with (DATA / name).open("w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerows(rows)


names = []
for locale in ("en_US", "de_DE"):
    provider = importlib.import_module("faker.providers.person." + locale).Provider
    for kind, attr in [
        ("male", "first_names_male"),
        ("female", "first_names_female"),
        ("last", "last_names"),
    ]:
        for i, value in enumerate(dict.fromkeys(getattr(provider, attr)), 1):
            names.append((locale, kind, i, value))
write("names.csv", names)

